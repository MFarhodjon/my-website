export function validatePersonalityData() {
  const errors = [];
  const questionIds = new Set();
  const choiceIds = new Set();
  const gifIds = [];

  if (questions.length !== 12) errors.push(`Expected 12 questions, found ${questions.length}.`);

  questions.forEach((question) => {
    if (questionIds.has(question.id)) errors.push(`Duplicate question id: ${question.id}.`);
    questionIds.add(question.id);
    if (question.choices.length !== 3) errors.push(`${question.id} must have exactly 3 choices.`);

    question.choices.forEach((choice) => {
      if (choiceIds.has(choice.id)) errors.push(`Duplicate choice id: ${choice.id}.`);
      choiceIds.add(choice.id);
      const asset = reactionAssets[choice.gif];
      if (!asset) {
        errors.push(`Missing reaction asset for ${question.id}/${choice.id}: ${choice.gif}.`);
        return;
      }
      if (!asset.id || !asset.page.includes(asset.id)) errors.push(`Invalid GIPHY page for ${choice.gif}.`);
      gifIds.push(asset.id);
    });
  });

  if (choiceIds.size !== 36) errors.push(`Expected 36 choices, found ${choiceIds.size}.`);
  if (gifIds.length !== 36) errors.push(`Expected 36 assigned GIFs, found ${gifIds.length}.`);
  if (new Set(gifIds).size !== gifIds.length) errors.push('Every answer must use a globally unique GIF.');
  if (gifIds.includes(prankGif.id)) errors.push('The ending prank GIF must not repeat an answer GIF.');
  if (!prankGif.page.includes(prankGif.id)) errors.push('Invalid prank GIF page.');

  if (errors.length) throw new Error(`Invalid personality game data:\n- ${errors.join('\n- ')}`);
  return true;
}
